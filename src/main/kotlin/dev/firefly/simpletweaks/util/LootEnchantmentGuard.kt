package dev.firefly.simpletweaks.util

import dev.firefly.simpletweaks.compat.FSTLog
import dev.firefly.simpletweaks.enchantments.generated.GeneratedEnchantments
import net.minecraft.component.DataComponentTypes
import net.minecraft.component.type.ItemEnchantmentsComponent
import net.minecraft.item.ItemStack

/**
 * Chest loot uses `enchant_with_levels` / `enchant_randomly`; when a loot table leaves `options` out, the game
 * rolls from **every registered enchantment** and only filters by `isAcceptableItem`. Our `non_treasure` /
 * `in_enchanting_table` tags are never consulted on that path, which is how a creative-only enchantment can
 * come out of a dungeon chest. Both loot functions hand their result through here before it reaches a player.
 */
object LootEnchantmentGuard {

    /** Enchantments that must never be generated by loot, trading or fishing. */
    private val CREATIVE_ONLY = setOf(GeneratedEnchantments.INFINITE_POWER)

    private fun isCreativeOnly(entry: net.minecraft.registry.entry.RegistryEntry<net.minecraft.enchantment.Enchantment>): Boolean =
        CREATIVE_ONLY.any { entry.matchesKey(it) }

    @JvmStatic
    fun strip(stack: ItemStack): ItemStack {
        if (stack.isEmpty) return stack
        val enchantments = stack.get(DataComponentTypes.ENCHANTMENTS) ?: return stack
        if (enchantments.getEnchantments().none(::isCreativeOnly)) return stack

        val builder = ItemEnchantmentsComponent.Builder(enchantments)
        builder.remove(::isCreativeOnly)
        stack.set(DataComponentTypes.ENCHANTMENTS, builder.build())
        FSTLog.log("Loot") { "outcome=stripped, item=${stack.item}, removed=${CREATIVE_ONLY.size}" }
        return stack
    }
}
