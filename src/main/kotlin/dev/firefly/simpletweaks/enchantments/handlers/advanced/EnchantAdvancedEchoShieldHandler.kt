/** The advanced form of this enchantment: its top tier plus an effect of its own. */
@ModEnchantment(
    id = "advanced_echo_shield",
    category = EnchantCategory.ADVANCED_MYTHIC,
    type = EnchantType.ARMOR,
    maxLevel = 4,
    ladderBase = 5,
    weight = EnchantItemWeights.ADVANCED_MYTHIC,
    damagePerLevel = 0.0,
    anvilCost = 12,
    minCostBase = 35,
    minCostPerLevel = 15,
    supportedItems = EnchantSupportedItemTags.ARMOR,
    slots = [EnchantSlot.ARMOR],
    order = 96,
)
object EnchantAdvancedEchoShieldHandler : Listenable {

    private const val BASE_LEVEL = 5

    @SubscribeEvent
    fun onLivingDamage(e: LivingDamageEvent) {
        if (e.invalid) return
        if (e.source.isAuxiliaryDamage()) return
        val player = e.entityLiving as? PlayerEntity ?: return
        var level = 0
        for (slot in EquipmentSlot.entries) {
            if (slot.type != EquipmentSlot.Type.HUMANOID_ARMOR) continue
            level += getItemSpecificEnchantLevel(player.getEquippedStack(slot), GeneratedEnchantments.ADVANCED_ECHO_SHIELD)
        }
        if (level <= 0) return
        val before = e.amount
        e.amount *= (1f - 0.02f * (BASE_LEVEL + level)).coerceAtLeast(0f)
        val saved = before - e.amount
        val attacker = e.source.attacker as? net.minecraft.entity.LivingEntity
        if (saved > 0f && attacker != null) attacker.damageElemental(player, ModDamageTypes.TRUE_DAMAGE, saved * 0.3f)
        FSTLog.log("AdvancedEchoShieldHandler") { "player=${player.name.string}, level=$level, damage=$before->${e.amount}, outcome=applied" }
    }
}